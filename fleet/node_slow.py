"""fleet/node_slow.py - a server that answers, eventually.

This node is up and it is not broken. It is just slow: every request to /health
sits for ten seconds before replying.

Ten seconds is long enough to matter. A check with no timeout will wait for it,
and while it waits your whole run is blocked. That is why every network call in
this project sets a timeout from the first line you write, not as a fix added
later.

There is a reward hidden here. If you raise your timeout above ten seconds, this
node does answer - and what it says is worth seeing. Its disk is nearly full.
A node can be slow *and* have something else wrong with it, and an engineer who
gives up at the timeout never finds out.

You do not edit this file. The delay is deliberate.
"""

import logging
import time

from flask import Flask, jsonify

PORT = 8803
NODE_NAME = "fleet-node-03"

# Long enough that a sensible timeout trips first. Your default timeout in
# targets.yaml is 2 seconds, so this node times out unless you change it.
RESPONSE_DELAY_SECONDS = 10

# This node is nearly out of disk. With the default threshold of 85 percent it
# is over the line, so a group that waits long enough to hear from it finds a
# second problem behind the first.
DISK_TOTAL_GB = 80
DISK_USED_GB = 73
DISK_PERCENT_USED = 91

logging.basicConfig(
    level=logging.INFO,
    format=f"%(asctime)s %(levelname)-8s [{NODE_NAME}] %(message)s",
)
log = logging.getLogger(NODE_NAME)

app = Flask(NODE_NAME)


@app.route("/")
def index():
    """Answers immediately. Only the health endpoint is slow."""
    return jsonify({"node": NODE_NAME, "message": "serving traffic"})


@app.route("/health")
def health():
    """Sleeps, then answers 200 with a disk figure over the threshold."""
    log.info("health check received - sleeping for %ds", RESPONSE_DELAY_SECONDS)
    time.sleep(RESPONSE_DELAY_SECONDS)
    return jsonify(
        {
            "node": NODE_NAME,
            "status": "ok",
            "version": "1.4.2",
            "disk": {
                "total_gb": DISK_TOTAL_GB,
                "used_gb": DISK_USED_GB,
                "percent_used": DISK_PERCENT_USED,
            },
        }
    )


if __name__ == "__main__":
    log.info("starting on port %d - /health sleeps %ds on purpose",
             PORT, RESPONSE_DELAY_SECONDS)
    app.run(host="127.0.0.1", port=PORT)
