"""fleet/node_broken.py - a server that is up but not well.

This node is running. Something is listening on its port. A check that only
asks "is the port open?" will call it healthy.

It is not healthy. Every request to /health returns 500.

This is the most important node in the fleet, because it is the one that proves
a reachability check is not a health check. Real services fail like this
constantly: the process is alive, the port is open, and the thing behind it - a
database, a queue, a disk - is broken.

You do not edit this file. The 500 is deliberate.
"""

import logging

from flask import Flask, jsonify

PORT = 8802
NODE_NAME = "fleet-node-02"

logging.basicConfig(
    level=logging.INFO,
    format=f"%(asctime)s %(levelname)-8s [{NODE_NAME}] %(message)s",
)
log = logging.getLogger(NODE_NAME)

app = Flask(NODE_NAME)


@app.route("/")
def index():
    """Still serving, which is part of what makes this node convincing.

    A service can be fine on one route and broken on another. That is why the
    health endpoint exists as a separate thing to check.
    """
    return jsonify({"node": NODE_NAME, "message": "serving traffic"})


@app.route("/health")
def health():
    """Always fails, with a 500 and a body explaining why.

    The body matters. "500" alone tells an engineer that something is wrong;
    the detail line tells them where to look. When you write your own services
    later in the course, put the reason in the body.
    """
    body = {
        "node": NODE_NAME,
        "status": "error",
        "detail": "database connection pool exhausted",
    }
    return jsonify(body), 500


if __name__ == "__main__":
    log.info("starting on port %d - /health returns 500 on purpose", PORT)
    app.run(host="127.0.0.1", port=PORT)
